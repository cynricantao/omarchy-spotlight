const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const logic = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, 'Logic.js'), 'utf8').replace(/^\.pragma library\s*/, ''), logic);
assert.equal(typeof logic.acceptMenuResponse, 'function', 'Native menus must gate responses by both query and submenu');
assert.equal(logic.acceptMenuResponse({query:'> ',menu:'learn'}, '> ', true, 'learn'), true);
assert.equal(logic.acceptMenuResponse({query:'> ',menu:'style'}, '> ', true, 'learn'), false);
assert.equal(logic.acceptMenuResponse({query:'> old',menu:'learn'}, '> new', true, 'learn'), false);
assert.equal(logic.acceptMenuResponse({query:'> ',menu:'learn'}, '> ', false, 'learn'), false);
assert.equal(logic.acceptMenuResponse({query:'> '}, '> ', true, 'learn'), false);
assert.equal(logic.acceptMenuResponse(null, '> ', true, 'learn'), false);
console.log('PASS: menu response gating rejects stale submenu, query, closed and malformed responses');
assert.equal(typeof logic.menuTarget, 'function', 'Menu results must navigate without action dispatch');
assert.equal(logic.menuTarget({kind:'menu',value:'trigger.capture'}), 'trigger.capture');
assert.equal(logic.menuTarget({kind:'menu-action',value:'system.shutdown'}), '');
assert.equal(logic.menuTarget({kind:'menu',value:''}), '');
assert.equal(logic.menuTarget(null), '');
assert.equal(typeof logic.confirmedSelection, 'function', 'Disruptive actions need explicit confirmation');
const risky={kind:'menu-action',id:'omarchy:system.shutdown',value:'system.shutdown',requiresConfirmation:true,actionToken:'token'};
assert.equal(logic.confirmedSelection(risky,false), null);
assert.equal(logic.confirmedSelection(risky,'true'), null);
assert.equal(logic.confirmedSelection({kind:'menu',requiresConfirmation:true},true), null);
assert.equal(logic.confirmedSelection(null,true), null);
const accepted=logic.confirmedSelection(risky,true);
assert.equal(accepted.confirmed,true);
assert.equal(accepted.actionToken,'token');
assert.equal(risky.confirmed,undefined);
const grouped=logic.sectionize([{kind:'action',id:'home'},risky,{kind:'menu',id:'learn'}], 'All');
assert.equal(grouped.items.length,3, 'Native menu rows must not disappear from mixed search');
assert.equal(grouped.sections[1].title,'Actions');
console.log('PASS: navigation never dispatches, cancellation creates no action, confirmation preserves token and grouping');
assert.equal(typeof logic.statusTooltipUseful,'function','Ready state should not create a warning-like tooltip');
assert.equal(logic.statusTooltipUseful('', 'ready'),false);
assert.equal(logic.statusTooltipUseful('', 'Ready'),false);
assert.equal(logic.statusTooltipUseful('', ''),false);
assert.equal(logic.statusTooltipUseful('', 'partial'),true);
assert.equal(logic.statusTooltipUseful('Menu unavailable', 'ready'),true);
console.log('PASS: quiet ready status, meaningful error/coverage tooltips');
